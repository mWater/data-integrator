-- Kit 5 adds MapView's onFeatureClick and themes MapLibre popups, which is a
-- change to kit.js and kit.css. Those are served immutable for a year under
-- /kit/:version, and the version in that path is only a cache key: the server
-- always resolves to the current asset files. So a dashboard still stamped
-- with kit_version 4 asks for bytes the browser already cached, and would
-- keep rendering white-on-white popups until its cache expired.
--
-- Repointing every stored version is safe precisely because the path version
-- does not select an asset: these bundles already run against the current kit
-- at runtime. This only corrects the cache key they ask under.
UPDATE app.dashboard_versions SET kit_version = '5' WHERE kit_version <> '5';
